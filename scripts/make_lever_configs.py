"""Writes configs/levers_<env>.json: batch 1 of the on-shift lever study, one config per environment.

    python scripts/make_lever_configs.py [--stats_root '$SCRATCH']

Per shift: a legacy-G split, a fix-only split, a from-scratch run, 13 single levers and 2 stacks (18 conditions),
each on 5 seeds. `stats_root` holds the results folders the warm-start lever (L06) reads on the cluster.
"""
import argparse, json, os

SEEDS = [18606, 16858, 63790, 15097, 62693]
LR = {
    "Hopper-v4": {"actor_lr": 1.1e-5, "critic_lr": 7.7e-5, "alpha_lr": 0.3},
    "Ant-v4": {"actor_lr": 0.0063, "critic_lr": 0.0087, "alpha_lr": 0.07},
    "Humanoid-v4": {"actor_lr": 0.0063, "critic_lr": 0.0087, "alpha_lr": 0.07},
}
# env -> (N, switch step), and the shifts to test: name -> (mods, warm-start source run as "<results folder>/<name>")
RUN = {"Hopper-v4": (6_000_000, 3_000_000), "Ant-v4": (12_000_000, 6_000_000), "Humanoid-v4": (12_000_000, 6_000_000)}
ANT_LIMB = {"mass": {"front_left_leg": 0.1175, "aux_1": 0.1175, "4": 0.2028}}
R24, R18 = "results_24M_10_26_2026", "results_limb_18m"
SHIFTS = {
    "Hopper-v4": {"gear2x": ({"gear_scale": 2.0}, f"{R24}/gear2x"), "heavy": ({"mass_scale": 2.0}, f"{R24}/heavy")},
    "Ant-v4": {"gear2x": ({"gear_scale": 2.0}, f"{R24}/gear2x"), "limb_heavy": (ANT_LIMB, f"{R18}/base_to_limb_heavy")},
    "Humanoid-v4": {"gear2x": ({"gear_scale": 2.0}, f"{R24}/gear2x"), "heavy": ({"mass_scale": 2.0}, f"{R24}/heavy")},
}

SHRINK_OBS = {"action": "shrink_obs_norm", "count": 1000}
SHRINK_SCALER = {"action": "shrink_td_scaler", "steps": 1000, "episodes": 10}
RESET_ADAM = {"action": "reset_adam", "net": "both"}
CRITIC_X10 = {"action": "lr_boost", "net": "critic", "k": 10, "steps": 200_000}
ACTOR_FREEZE = {"action": "lr_boost", "net": "actor", "k": 0, "steps": 50_000, "mode": "hold"}
BETA2 = {"action": "set_beta2", "beta2": 0.99, "steps": 200_000}


def levers(env, shift, stats_root):
    """name -> extra arguments, for the 13 singles and 2 stacks"""
    N, switch = RUN[env]
    src = f"{stats_root}/{SHIFTS[env][shift][1]}-{env}-{SEEDS[0]}-*"
    warm = {"action": "load_stats", "path": f"{src}/*_model_{switch // 1_000_000}M.pt", "scaler_path": f"{src}/checkpoint.pt"}
    return {
        "L02_shrink_obs": {"on_shift": [SHRINK_OBS]},
        "L02_hard_obs": {"on_shift": [{"action": "shrink_obs_norm", "count": 0}]},
        "L03_cap_obs": {"obs_norm_cap": 100_000},
        "L04_shrink_scaler": {"on_shift": [SHRINK_SCALER]},
        "L05_cap_scaler": {"td_scaler_cap": [100_000, 100]},
        "L06_warm_start": {"on_shift": [warm]},
        "L07_reset_adam": {"on_shift": [RESET_ADAM]},
        "L08_critic_x3": {"on_shift": [{**CRITIC_X10, "k": 3}]},
        "L08_critic_x10": {"on_shift": [CRITIC_X10]},
        "L09_actor_freeze": {"on_shift": [ACTOR_FREEZE]},
        "L10_actor_delayed": {"on_shift": [{"action": "lr_boost", "net": "actor", "k": 5, "steps": 200_000, "delay": 50_000}]},
        "L11_adaptive": {"adaptive_lr": [1000, 100_000, 10]},
        "L12_beta2": {"on_shift": [BETA2]},
        "S01_stats_stack": {"on_shift": [SHRINK_OBS, SHRINK_SCALER, RESET_ADAM]},
        "S02_sink": {"on_shift": [SHRINK_OBS, SHRINK_SCALER, RESET_ADAM, CRITIC_X10, ACTOR_FREEZE, BETA2]},
    }


def config(env, stats_root, smoke=False):
    N, switch = RUN[env]
    experiments = []
    for shift, (mods, _) in SHIFTS[env].items():
        if smoke and shift != "gear2x":
            continue
        schedule = [{"step": switch, "mods": mods}]
        experiments.append({"name": f"legacy-{shift}", "schedule": schedule, "legacy_g_reset": True})
        experiments.append({"name": f"fix-{shift}", "schedule": schedule})
        experiments.append({"name": f"scratch-{shift}", "env_mods": mods})
        for name, extra in levers(env, shift, stats_root).items():
            experiments.append({"name": f"{name}-{shift}", "schedule": schedule, **extra})
    cfg = {
        "_comment": [
            f"Lever study batch 1 on {env}: {N // 1_000_000}M steps, physics switch at {switch // 1_000_000}M.",
            "Per shift: legacy-G split, fix-only split, from-scratch, 13 single levers, 2 stacks = 18 conditions x 5 seeds.",
            "Generated by scripts/make_lever_configs.py; edit that and regenerate rather than this file.",
            "L06_warm_start loads normaliser stats from the from-scratch run's snapshot at the switch step and scaler stats",
            "from its final checkpoint (Ant limb_heavy has no from-scratch run: it uses the 18M base_to_limb_heavy run).",
        ],
        "defaults": {
            "N": N,
            "seeds": SEEDS,
            "gamma": 0.99,
            "beta1": 0.0,
            "normalize_obs": True,
            "pnorm": True,
            "scaled_td": True,
            "n_eval": 2,
            "video_every": switch,
            "save_model": True,
            "save_model_every": 1_000_000,
            "dense_window": [20_000, 200_000],
        },
        "envs": {env: LR[env]},
        "experiments": experiments,
    }
    if smoke:  # every condition once, on a short run: 18 runs, gear2x only, one seed
        for e in experiments:
            if "schedule" in e:
                e["schedule"][0]["step"] = 20_000
        cfg["_comment"] = [
            "Smoke test of configs/levers_<env>.json: every condition once on Hopper gear2x, 40k steps, switch at 20k.",
            "Debug partition: sbatch -p debug --time=00:30:00 --export=ALL,CONFIG=$HOME/cf-avg/configs/levers_smoke.json"
            " $HOME/cf-avg/scripts/trillium/avg_multi.sh",
        ]
        cfg["defaults"].update(N=40_000, seeds=SEEDS[:1], n_eval=1, video_every=20_000, dense_window=[5_000, 15_000], checkpoint=10_000)
    return cfg


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--stats_root", default="$SCRATCH", help=f"Folder holding {R24} and {R18} (the warm-start sources)")
    p.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "configs"))
    args = p.parse_args()
    todo = [(f"levers_{env.split('-')[0].lower()}", env, False) for env in RUN] + [("levers_smoke", "Hopper-v4", True)]
    for name, env, smoke in todo:
        cfg = config(env, args.stats_root, smoke)
        path = os.path.join(args.out, f"{name}.json")
        with open(path, "w") as f:
            json.dump(cfg, f, indent=1)
        print(f"{path}: {len(cfg['experiments'])} experiments x {len(cfg['defaults']['seeds'])} seeds")
