"""Critic eligibility trace study: writes configs/traces_2026-11-26/traces_<env>_<shift>.json for every environment of the
shift study. Each config fits one Trillium node.

    python scripts/configs/make_trace_configs.py [--env Hopper-v4 ...] [--lambdas 0 0.5 0.8 0.9] [--lr_mults 1 0.5 0.25 0.125]
    bash scripts/trillium/submit_traces.sh                                  # one job per config

Every cell of critic_lambda x critic_lr (a multiple of the tuned value) is run on the shift study's conditions,
with the same hyperparameters, run lengths, seeds and legacy G reset:
    <cell>_legacy-none       baseline: no shift, the whole run            (traces_<env>_none.json)
    <cell>_legacy-<shift>    base -> shifted at the halfway step          (traces_<env>_<shift>.json)
    <cell>_scratch-<shift>   the shifted dynamics from step 0 to the end  (traces_<env>_<shift>.json)
<cell> is lam<lambda>_clr<mult>x; lam0_clr1x is the shift study's own run. Shifts are the study's core and body
shifts of each environment. No levers.
"""
import argparse, json, os

from make_shift_study_configs import CORE, ENVS, SEEDS, short

NODE_RUNS = 188


def cells(lambdas, lr_mults, lr):
    """name -> arguments of one critic_lambda x critic_lr cell"""
    out = {}
    for lam in lambdas:
        for m in lr_mults:
            args = {"critic_lr": float(f"{lr * m:.3g}")}
            if lam:
                args["critic_lambda"] = lam
            out[f"lam{lam:g}_clr{m:g}x"] = args
    return out


def configs(env, lambdas, lr_mults, n_seeds):
    """shift name -> config, plus "none" for the baseline"""
    spec = ENVS[env]
    N = spec["N"]
    switch = N // 2
    grid = cells(lambdas, lr_mults, spec["hyp"]["critic_lr"])
    seeds = SEEDS[:n_seeds]
    shifts = {**CORE, **spec.get("core", {}), **spec["shifts"]}
    out = {}
    for shift, mods in {"none": None, **shifts}.items():
        experiments = []
        for cell, args in grid.items():
            if mods is None:
                experiments.append({"name": f"{cell}_legacy-none", **args})
            else:
                experiments.append({"name": f"{cell}_legacy-{shift}", "schedule": [{"step": switch, "mods": mods}], **args})
                experiments.append({"name": f"{cell}_scratch-{shift}", "env_mods": mods, **args})
        runs = len(experiments) * len(seeds)
        nodes = -(-runs // NODE_RUNS)
        what = "the baseline, no shift" if mods is None else f"the {shift} shift, base -> shifted at {switch} and shifted from step 0"
        out[shift] = {
            "_comment": [
                f"Critic eligibility trace on {env}, {what}: {N} steps per run, {len(seeds)} seed(s), legacy G reset in every run.",
                f"critic_lambda {lambdas} x critic_lr at {lr_mults} of the tuned {spec['hyp']['critic_lr']:g}.",
                f"{len(experiments)} conditions x {len(seeds)} seed(s) = {runs} runs, "
                + ("one Trillium node." if nodes == 1 else f"{nodes} Trillium nodes (SHARD=1/{nodes} ...)."),
                "Generated by scripts/configs/make_trace_configs.py; regenerate rather than edit.",
            ],
            "defaults": {
                "N": N,
                "seeds": seeds,
                "normalize_obs": True,
                "pnorm": True,
                "scaled_td": True,
                "legacy_g_reset": True,
                "n_eval": 2,
                "video_every": switch,
                "save_model": True,
                "save_model_every": 1_000_000,
                "dense_window": [min(200_000, (N - switch) // 10) // 10, min(200_000, (N - switch) // 10)],
            },
            "envs": {env: spec["hyp"]},
            "experiments": experiments,
        }
    return out


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--env", nargs="*", default=list(ENVS), help="Default: every env in ENVS")
    p.add_argument("--lambdas", nargs="*", type=float, default=[0, 0.5, 0.8, 0.9])
    p.add_argument("--lr_mults", nargs="*", type=float, default=[1, 0.5, 0.25, 0.125], help="Multiples of the tuned critic_lr")
    p.add_argument("--n_seeds", default=5, type=int, help=f"1..{len(SEEDS)}")
    p.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "..", "configs", "traces_2026-11-26"))
    args = p.parse_args()
    os.makedirs(args.out, exist_ok=True)
    total = 0
    for env in args.env:
        cfgs = configs(env, args.lambdas, args.lr_mults, args.n_seeds)
        for shift, cfg in cfgs.items():
            path = os.path.join(args.out, f"traces_{short(env)}_{shift}.json")
            with open(path, "w") as f:
                json.dump(cfg, f, indent=1)
        runs = sum(len(c["experiments"]) * args.n_seeds for c in cfgs.values())
        total += runs
        print(f"{env}: {len(cfgs)} configs, {runs} runs")
    print(f"total: {total} runs")
