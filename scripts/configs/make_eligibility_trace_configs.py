"""Eligibility trace study on every environment: writes configs/eligibility_trace_real_2026-11-27/etr_<env>_<k>.json.

    python scripts/configs/make_eligibility_trace_configs.py [--env Hopper-v4 ...] [--lambdas 0.5 0.75] [--no_scratch]
    bash scripts/trillium/submit_etr.sh                                     # one job per config

Each critic_lambda runs at the tuned critic_lr on the shift study's conditions, with its hyperparameters, run
lengths, seeds and legacy G reset:
    lam<l>_clr1x_legacy-none       trace from step 0; no shift, the whole run
    lam<l>_clr1x_legacy-<shift>    trace from step 0; base -> shifted at the halfway step
    lam<l>_clr1x_scratch-<shift>   trace from step 0; the shifted dynamics from step 0 to the end
    lam<l>on_clr1x_legacy-<shift>  no trace until the switch, trace switched on with it (set_critic_lambda lever)
The run without a trace (lam0_clr1x) is the shift study's own legacy/scratch run on the same seeds, so it is not
repeated unless 0 is passed in --lambdas. Shifts are the study's, minus those in SKIP. Each config fits one
Trillium node; an environment with more runs than that is split into etr_<env>_1, _2.
"""
import argparse, json, os

from make_shift_study_configs import ENVS, short
from make_trace_configs import NODE_RUNS, configs

# class 4 (impaired) in the shift study of 2026-11-26, results_study_runs_analysis/classes.csv
IMPAIRED = {
    "Ant-v4": ["all_flipped", "gear2x"],
    "HalfCheetah-v4": ["all_flipped", "dead_joint", "limb_heavy", "stiff_springs"],
    "Humanoid-v4": ["all_flipped"],
    "HumanoidStandup-v4": ["all_flipped", "flipped_joint", "loose", "payload"],
    "dmc-finger-spin": ["all_flipped"],
    "dmc-quadruped-run": ["all_flipped", "limb_heavy", "payload"],
}
UNSTABLE = {"dmc-quadruped-run": ["stiff"]}  # damping x5 blows up the simulation; no study run finished
SKIP = {env: IMPAIRED.get(env, []) + UNSTABLE.get(env, []) for env in ENVS}


def chunks(env, lambdas, n_seeds, scratch):
    """The environment's configs, each at most one node of runs"""
    per_shift = configs(env, lambdas, [1], n_seeds)
    dropped = [s for s, mods in ENVS[env].get("core", {}).items() if mods is None]  # core shifts the env does not have
    shifts = [s for s in per_shift if s not in SKIP[env] + dropped]
    groups = {s: [e for e in per_shift[s]["experiments"] if scratch or "_scratch-" not in e["name"]] for s in shifts}
    for s in shifts:  # trace switched on at the switch
        for lam in lambdas:
            ref = next((e for e in groups[s] if "schedule" in e), None)
            if ref and lam > 0:
                groups[s].append({"name": f"lam{lam:g}on_clr1x_legacy-{s}", "schedule": ref["schedule"], "critic_lr": ref["critic_lr"],
                                  "on_shift": [{"action": "set_critic_lambda", "lam": lam}]})
    total = sum(len(g) for g in groups.values()) * n_seeds
    n_parts = -(-total // NODE_RUNS)
    parts, target = [[]], total / n_parts
    for s in shifts:  # whole shifts per part, parts of about equal size
        if len(parts) < n_parts and len(parts[-1]) and (sum(len(groups[x]) for x in parts[-1]) + len(groups[s]) / 2) * n_seeds > target:
            parts.append([])
        parts[-1].append(s)
    out = []
    for part in parts:
        cfg = dict(per_shift["none"])
        cfg["experiments"] = [e for s in part for e in groups[s]]
        runs = len(cfg["experiments"]) * n_seeds
        assert runs <= NODE_RUNS, (env, runs)
        cfg["_comment"] = [
            f"Eligibility trace study on {env}: critic_lambda {lambdas} at the tuned critic_lr, {cfg['defaults']['N']} steps per run, {n_seeds} seed(s), legacy G reset.",
            f"Conditions: {', '.join('no shift' if s == 'none' else s for s in part)}" + (" (base -> shifted at the halfway step, and shifted from step 0)." if scratch else " (base -> shifted at the halfway step)."),
            "Trace from step 0 (lam<l>_...), or switched on at the switch after training without one (lam<l>on_...).",
            f"Left out: {', '.join(SKIP[env]) or 'nothing'} (class 4 in the shift study, or unstable). The run without a trace is the shift study's.",
            f"{len(cfg['experiments'])} conditions x {n_seeds} seed(s) = {runs} runs, one Trillium node.",
            "Generated by scripts/configs/make_eligibility_trace_configs.py; regenerate rather than edit.",
        ]
        out.append(cfg)
    return out, shifts


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--env", nargs="*", default=list(ENVS))
    p.add_argument("--lambdas", nargs="*", type=float, default=[0.5, 0.75])
    p.add_argument("--n_seeds", type=int, default=5)
    p.add_argument("--no_scratch", action="store_true", help="Leave out the from-scratch runs in the shifted dynamics")
    p.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "..", "configs", "eligibility_trace_real_2026-11-27"))
    args = p.parse_args()
    os.makedirs(args.out, exist_ok=True)
    total = 0
    for env in args.env:
        cfgs, shifts = chunks(env, args.lambdas, args.n_seeds, not args.no_scratch)
        for k, cfg in enumerate(cfgs, 1):
            with open(os.path.join(args.out, f"etr_{short(env)}_{k}.json"), "w") as f:
                json.dump(cfg, f, indent=1)
        runs = [len(c["experiments"]) * args.n_seeds for c in cfgs]
        total += sum(runs)
        print(f"{env}: {len(shifts) - 1} shifts, {len(cfgs)} config(s), runs {runs}")
    print(f"total: {total} runs")
