"""Writes configs/priv_<env>.json: batch 2 of the lever study, levers driven by privileged targets from batch 1.

    python scripts/make_privileged_configs.py [--legacy] [--stats_root '$SCRATCH/results'] [--targets configs/privileged_targets.json]

Per shift: fix-only split, from-scratch run, the batch-1 obs-shrink reference, 4 privileged singles and 6 stacks
(13 conditions) on 5 seeds. `stats_root` holds the batch-1 result folders (the from-scratch runs' 1M snapshots give
the post-shift observation statistics). Targets come from scripts/analysis/privileged_targets.py.
"""
import argparse, json, os, sys

sys.path.insert(0, os.path.dirname(__file__))
from make_lever_configs import SEEDS, LR, RUN, SHIFTS, SHRINK_OBS, RESET_ADAM

ALPHA_LOW = {"action": "set_alpha", "k": 0.1, "steps": 300_000}


def levers(env, shift, stats_root, tg):
    """name -> extra arguments"""
    src = f"{stats_root}/scratch-{shift}-{env}-{SEEDS[0]}-*"
    priv_obs = {"action": "load_stats", "path": f"{src}/*_model_1M.pt", "obs_only": True, "count": 10_000}
    track = {"action": "alpha_track", "target": tg["entropy_target"], "steps": 500_000, "eta": 1e-4, "window": 1000,
             "min": 0.02, "max": 2.0, "release": 100_000}
    offset = {"action": "reward_offset", "offset": tg["reward_offset"], "steps": 300_000}
    return {
        "L02_shrink_obs": {"on_shift": [SHRINK_OBS]},
        "P1_alpha_x0.1": {"on_shift": [ALPHA_LOW]},
        "P1_alpha_x0.3": {"on_shift": [{**ALPHA_LOW, "k": 0.3}]},
        "P2_alpha_track": {"on_shift": [track]},
        "P3_reward_offset": {"on_shift": [offset]},
        "P4_priv_obs": {"on_shift": [priv_obs]},
        "P5_obs_alpha": {"on_shift": [priv_obs, ALPHA_LOW]},
        "P6_obs_track": {"on_shift": [priv_obs, track]},
        "P7_obs_offset": {"on_shift": [priv_obs, offset]},
        "P8_obs_alpha_offset": {"on_shift": [priv_obs, ALPHA_LOW, offset]},
        "P9_obs_track_offset": {"on_shift": [priv_obs, track, offset]},
        "P10_obs_track_adam": {"on_shift": [priv_obs, track, RESET_ADAM]},
    }


def config(env, stats_root, targets, smoke=False, legacy=False):
    """legacy=True: every run with the old G reset (no reset on truncation), paired against the legacy base"""
    N, switch = RUN[env]
    experiments = []
    g = {"legacy_g_reset": True} if legacy else {}
    for shift, (mods, _) in SHIFTS[env].items():
        if smoke and shift != "gear2x":
            continue
        schedule = [{"step": switch, "mods": mods}]
        experiments.append({"name": f"{'legacy' if legacy else 'fix'}-{shift}", "schedule": schedule, **g})
        experiments.append({"name": f"scratch-{shift}", "env_mods": mods, **g})
        for name, extra in levers(env, shift, stats_root, targets[env][shift]).items():
            experiments.append({"name": f"{name}-{shift}", "schedule": schedule, **extra, **g})
    cfg = {
        "_comment": [
            f"Lever study batch 2 (privileged targets){' with the legacy G reset in every run' if legacy else ''} on {env}: {N // 1_000_000}M steps, physics switch at {switch // 1_000_000}M.",
            f"Per shift: {'legacy base' if legacy else 'fix-only split'}, from-scratch, batch-1 obs-shrink reference, 4 privileged singles, 6 stacks = 13 conditions x 5 seeds{' (analyse with --base legacy)' if legacy else ''}.",
            "Generated by scripts/make_privileged_configs.py from configs/privileged_targets.json; regenerate rather than edit.",
            "P4 loads the observation statistics of the from-scratch run's 1M snapshot (batch-1 results under stats_root).",
        ],
        "defaults": {
            "N": N, "seeds": SEEDS, "gamma": 0.99, "beta1": 0.0, "normalize_obs": True, "pnorm": True, "scaled_td": True,
            "n_eval": 2, "video_every": switch, "save_model": True, "save_model_every": 1_000_000, "dense_window": [20_000, 200_000],
        },
        "envs": {env: LR[env]},
        "experiments": experiments,
    }
    if smoke:
        for e in experiments:
            if "schedule" in e:
                e["schedule"][0]["step"] = 1500
        pre = "priv_legacy" if legacy else "priv"
        cfg["_comment"] = [f"Smoke test of configs/{pre}_<env>.json: every condition once on Hopper gear2x, 3000 steps, switch at 1500.",
                           f"Login node, ~2 min: CONFIG=configs/{pre}_smoke.json bash scripts/trillium/smoke_levers.sh"]
        cfg["defaults"].update(N=3000, seeds=SEEDS[:1], n_eval=1, video_every=1500, dense_window=[500, 1000], checkpoint=1000)
    return cfg


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--stats_root", default="$SCRATCH/results", help="Folder holding the batch-1 run folders (scratch-<shift>-<env>-<seed>-*)")
    p.add_argument("--targets", default=os.path.join(os.path.dirname(__file__), "..", "configs", "privileged_targets.json"))
    p.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "configs"))
    p.add_argument("--prefix", default=None, help="Config file prefix (default priv, or priv_legacy with --legacy)")
    p.add_argument("--legacy", action="store_true", help="Write configs/priv_legacy_<env>.json: every run with the old G reset")
    args = p.parse_args()
    prefix = args.prefix or ("priv_legacy" if args.legacy else "priv")
    targets = json.load(open(args.targets))
    todo = [(f"{prefix}_{env.split('-')[0].lower()}", env, False) for env in RUN] + [(f"{prefix}_smoke", "Hopper-v4", True)]
    for name, env, smoke in todo:
        cfg = config(env, args.stats_root, targets, smoke, args.legacy)
        path = os.path.join(args.out, f"{name}.json")
        with open(path, "w") as f:
            json.dump(cfg, f, indent=1)
        print(f"{path}: {len(cfg['experiments'])} experiments x {len(cfg['defaults']['seeds'])} seeds")
