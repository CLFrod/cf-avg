"""Writes configs/greedy_<env>.json (legacy G reset) and configs/greedy_fix_<env>.json (G-truncation fix): Greedy AC
(Neumann et al. 2023) as a shift-recovery method, plus the entropy-tracking conditions re-run with the corrected
controller, on the same 10 seeds.

    python scripts/make_greedy_configs.py [--stats_root '$SCRATCH/results'] [--targets configs/privileged_targets.json]

Per shift and world: the base; Greedy AC (N=30, top 3, plain Sarsa critic) switched on at the shift, alone, with the
observation-normaliser soft reset, for a 1M-step window, with a wide proposal, and with the soft critic; the best-of-30
execution-only control; Greedy AC from step 0 (stability check in its pre-shift half); and entropy tracking alone and
in its three batch-2 stacks. 12 conditions x 10 seeds x 2 shifts = 240 runs per config: submit as two shards.
Primary test: GAC_shift vs base on early_1M, Ant gear2x and Humanoid heavy; the rest is exploratory.
"""
import argparse, json, os, sys

sys.path.insert(0, os.path.dirname(__file__))
from make_lever_configs import SEEDS as SEEDS5, LR, RUN, SHIFTS, SHRINK_OBS
from make_privileged_configs import levers as priv_levers

SEEDS = SEEDS5 + [24601, 7331, 90210, 41275, 5812]
GAC = {"action": "greedy_ac", "N": 30, "rho": 0.1}
TRACKING = ["P2_alpha_track", "P6_obs_track", "P9_obs_track_offset", "P10_obs_track_adam"]


def conditions(env, shift, stats_root, targets):
    """name -> extra arguments"""
    priv = priv_levers(env, shift, stats_root, targets[env][shift])
    return {
        "GAC_shift": {"on_shift": [GAC]},
        "GAC_shift_obs": {"on_shift": [SHRINK_OBS, GAC]},
        "GAC_shift_1M": {"on_shift": [{**GAC, "steps": 1_000_000}]},
        "GAC_shift_wide": {"on_shift": [{**GAC, "proposal_std": 1.0}]},
        "GAC_shift_soft": {"on_shift": [{**GAC, "soft_critic": True}]},
        "BestOf30_shift": {"on_shift": [{"action": "best_of", "N": 30}]},
        "GAC_full": {"greedy_ac": [30, 0.1]},
        **{name: priv[name] for name in TRACKING},
    }


def config(env, stats_root, targets, legacy, smoke=False):
    N, switch = RUN[env]
    base = "legacy" if legacy else "fix"
    experiments = []
    for shift, (mods, _) in SHIFTS[env].items():
        if smoke and shift != "gear2x":
            continue
        schedule = [{"step": switch, "mods": mods}]
        experiments.append({"name": f"{base}-{shift}", "schedule": schedule})
        for name, extra in conditions(env, shift, stats_root, targets).items():
            experiments.append({"name": f"{name}-{shift}", "schedule": schedule, **extra})
    world = "legacy G reset" if legacy else "G-truncation fix"
    cfg = {
        "_comment": [
            f"Greedy AC as a shift-recovery method on {env} under the {world}: {N // 1_000_000}M steps, physics switch at {switch // 1_000_000}M.",
            f"Per shift: {base} base, GAC at the shift (alone, + obs soft reset, 1M window, wide proposal, soft critic), best-of-30 control, GAC from step 0,",
            "entropy tracking with the corrected controller alone and in its three stacks (P2, P6, P9, P10) = 12 conditions x 10 seeds.",
            "Greedy AC: N=30 samples from the proposal, top 3 by Q, plain Sarsa critic unless soft_critic. 240 runs: submit with SHARD=1/2 and SHARD=2/2.",
            f"Generated by scripts/make_greedy_configs.py; analyse with lever_recovery.py --base {base}. P6/P9/P10 load obs stats from stats_root.",
        ],
        "defaults": {
            "N": N, "seeds": SEEDS, "gamma": 0.99, "beta1": 0.0, "normalize_obs": True, "pnorm": True, "scaled_td": True,
            "legacy_g_reset": legacy, "n_eval": 2, "video_every": switch, "save_model": True, "save_model_every": 1_000_000,
            "dense_window": [20_000, 200_000],
        },
        "envs": {env: LR[env]},
        "experiments": experiments,
    }
    if smoke:
        for e in experiments:
            e["schedule"][0]["step"] = 1500
            for a in e.get("on_shift", []):
                if "steps" in a:
                    a["steps"] = 800
                if "release" in a:
                    a["release"] = 200
        pre = "greedy" if legacy else "greedy_fix"
        cfg["_comment"] = [f"Smoke test of configs/{pre}_<env>.json: every condition once on Hopper gear2x, 3000 steps, switch at 1500.",
                           f"Login node, ~1 min: CONFIG=configs/{pre}_smoke.json bash scripts/trillium/smoke_levers.sh"]
        cfg["defaults"].update(N=3000, seeds=SEEDS[:1], n_eval=1, video_every=1500, dense_window=[500, 1000], checkpoint=1000)
    return cfg


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--stats_root", default="$SCRATCH/results", help="Folder holding the batch-1 run folders (scratch-<shift>-<env>-<seed>-*)")
    p.add_argument("--targets", default=os.path.join(os.path.dirname(__file__), "..", "configs", "privileged_targets.json"))
    p.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "configs"))
    args = p.parse_args()
    targets = json.load(open(args.targets))
    for legacy, prefix in ((True, "greedy"), (False, "greedy_fix")):
        todo = [(f"{prefix}_{env.split('-')[0].lower()}", env, False) for env in RUN] + [(f"{prefix}_smoke", "Hopper-v4", True)]
        for name, env, smoke in todo:
            cfg = config(env, args.stats_root, targets, legacy, smoke)
            path = os.path.join(args.out, f"{name}.json")
            with open(path, "w") as f:
                json.dump(cfg, f, indent=1)
            print(f"{path}: {len(cfg['experiments'])} experiments x {len(cfg['defaults']['seeds'])} seeds")
