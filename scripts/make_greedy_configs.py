"""Writes configs/greedy_<env>.json: Greedy AC (Neumann et al. 2023) as a shift-recovery method, under the legacy G reset.

    python scripts/make_greedy_configs.py

Per shift, 10 seeds: the legacy base; Greedy AC (N=30, top 3, plain Sarsa critic) switched on at the shift, alone,
with the observation-normaliser soft reset, for a 1M-step window, with a wide proposal, and with the soft critic;
the best-of-30 execution-only control; and Greedy AC from step 0 (stability check in its pre-shift half).
Primary test: GAC_shift vs legacy on early_1M, Ant gear2x and Humanoid heavy; the rest is exploratory.
"""
import argparse, json, os, sys

sys.path.insert(0, os.path.dirname(__file__))
from make_lever_configs import SEEDS as SEEDS5, LR, RUN, SHIFTS, SHRINK_OBS

SEEDS = SEEDS5 + [24601, 7331, 90210, 41275, 5812]
GAC = {"action": "greedy_ac", "N": 30, "rho": 0.1}


def conditions():
    """name -> extra arguments"""
    return {
        "GAC_shift": {"on_shift": [GAC]},
        "GAC_shift_obs": {"on_shift": [SHRINK_OBS, GAC]},
        "GAC_shift_1M": {"on_shift": [{**GAC, "steps": 1_000_000}]},
        "GAC_shift_wide": {"on_shift": [{**GAC, "proposal_std": 1.0}]},
        "GAC_shift_soft": {"on_shift": [{**GAC, "soft_critic": True}]},
        "BestOf30_shift": {"on_shift": [{"action": "best_of", "N": 30}]},
        "GAC_full": {"greedy_ac": [30, 0.1]},
    }


def config(env, smoke=False):
    N, switch = RUN[env]
    experiments = []
    for shift, (mods, _) in SHIFTS[env].items():
        if smoke and shift != "gear2x":
            continue
        schedule = [{"step": switch, "mods": mods}]
        experiments.append({"name": f"legacy-{shift}", "schedule": schedule})
        for name, extra in conditions().items():
            experiments.append({"name": f"{name}-{shift}", "schedule": schedule, **extra})
    cfg = {
        "_comment": [
            f"Greedy AC as a shift-recovery method on {env}: {N // 1_000_000}M steps, physics switch at {switch // 1_000_000}M, legacy G reset in every run.",
            "Per shift: legacy base, GAC at the shift (alone, + obs soft reset, 1M window, wide proposal, soft critic), best-of-30 control, GAC from step 0 = 8 conditions x 10 seeds.",
            "Greedy AC: N=30 samples from the proposal, top 3 by Q, plain Sarsa critic unless soft_critic. Generated by scripts/make_greedy_configs.py; analyse with lever_recovery.py --base legacy.",
            "References to reuse from results_legacy_<env> (same first 5 seeds): scratch, L02_shrink_obs, L09_actor_freeze.",
        ],
        "defaults": {
            "N": N, "seeds": SEEDS, "gamma": 0.99, "beta1": 0.0, "normalize_obs": True, "pnorm": True, "scaled_td": True,
            "legacy_g_reset": True, "n_eval": 2, "video_every": switch, "save_model": True, "save_model_every": 1_000_000,
            "dense_window": [20_000, 200_000],
        },
        "envs": {env: LR[env]},
        "experiments": experiments,
    }
    if smoke:
        for e in experiments:
            e["schedule"][0]["step"] = 1500
            for a in e.get("on_shift", []):
                if "steps" in a:
                    a["steps"] = 800
        cfg["_comment"] = ["Smoke test of configs/greedy_<env>.json: every condition once on Hopper gear2x, 3000 steps, switch at 1500.",
                           "Login node, ~1 min: CONFIG=configs/greedy_smoke.json bash scripts/trillium/smoke_levers.sh"]
        cfg["defaults"].update(N=3000, seeds=SEEDS[:1], n_eval=1, video_every=1500, dense_window=[500, 1000], checkpoint=1000)
    return cfg


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "configs"))
    args = p.parse_args()
    todo = [(f"greedy_{env.split('-')[0].lower()}", env, False) for env in RUN] + [("greedy_smoke", "Hopper-v4", True)]
    for name, env, smoke in todo:
        cfg = config(env, smoke)
        path = os.path.join(args.out, f"{name}.json")
        with open(path, "w") as f:
            json.dump(cfg, f, indent=1)
        print(f"{path}: {len(cfg['experiments'])} experiments x {len(cfg['defaults']['seeds'])} seeds")
