"""Greedy AVG study: writes configs/gavg_<env>.json (one node each, ~185 runs) and configs/gavg_smoke.json.

    python scripts/make_gavg_configs.py [--stats_root '$SCRATCH/results'] [--targets configs/privileged_targets.json]

Greedy AVG = AVG with the Greedy AC actor update (N=30 proposal samples, top 3 by Q, plain Sarsa critic) from step 0.
All runs use the legacy G reset. Per env (Hopper 6M steps, Ant/Humanoid 12M, switch at half):
  1. Greedy AVG from scratch, no switch, 5 seeds: base dynamics (GACscratch-nomod) and each shifted dynamics
     (GACscratch-<shift>); the AVG counterparts are the 24M dynamics-suite runs.
  2. Greedy AVG with a switch at half, 10 seeds: GAC-<shift> for moon, gear2x, slippery, heavy.
  3. Greedy AVG + the methods that showed promise, 10 seeds: obs soft reset (all shifts), obs window (gear2x, heavy),
     privileged obs stats (gear2x, the one shift with a batch-1 from-scratch snapshot on every env).
Every method runs on all three envs with the same shifts.
  4. Legacy AVG with the same switches and seeds: legacy-<shift>.
Analyse with lever_recovery.py --base legacy (everything vs AVG) and --base GAC (methods vs Greedy AVG).
"""
import argparse, json, os, sys

sys.path.insert(0, os.path.dirname(__file__))
from make_lever_configs import SEEDS as SEEDS5, LR, RUN, SHRINK_OBS
from make_privileged_configs import levers as priv_levers

SEEDS = SEEDS5 + [24601, 7331, 90210, 41275, 5812]
GAC = {"greedy_ac": [30, 0.1]}
SUITE = {"moon": {"gravity": -1.62}, "gear2x": {"gear_scale": 2.0}, "slippery": {"friction_scale": 0.3}, "heavy": {"mass_scale": 2.0}}
WINDOW_SHIFTS = ("gear2x", "heavy")
PRIV_SHIFTS = ("gear2x",)  # the one shift with a batch-1 from-scratch snapshot on every env


def config(env, stats_root, targets, smoke=False):
    N, switch = RUN[env]
    experiments = [{"name": "GACscratch-nomod", "seeds": SEEDS[:5], **GAC}]
    shifts = {"gear2x": SUITE["gear2x"]} if smoke else SUITE
    for shift, mods in shifts.items():
        schedule = [{"step": switch, "mods": mods}]
        experiments.append({"name": f"GACscratch-{shift}", "seeds": SEEDS[:5], "env_mods": mods, **GAC})
        experiments.append({"name": f"legacy-{shift}", "schedule": schedule})
        experiments.append({"name": f"GAC-{shift}", "schedule": schedule, **GAC})
        experiments.append({"name": f"GACx_obs_soft-{shift}", "schedule": schedule, **GAC, "on_shift": [SHRINK_OBS]})
        if shift in WINDOW_SHIFTS:
            experiments.append({"name": f"GACx_obs_window-{shift}", "schedule": schedule, **GAC, "obs_norm_cap": 100_000})
        if shift in PRIV_SHIFTS:
            priv = priv_levers(env, shift, stats_root, targets[env][shift])
            experiments.append({"name": f"GACx_priv_obs-{shift}", "schedule": schedule, **GAC, **priv["P4_priv_obs"]})
    cfg = {
        "_comment": [
            f"Greedy AVG study on {env}, legacy G reset: {N // 1_000_000}M steps, switch at {switch // 1_000_000}M. Greedy AVG = Greedy AC actor update (N=30, top 3, plain Sarsa critic) from step 0.",
            "GACscratch-*: Greedy AVG from scratch, no switch (5 seeds; AVG counterparts = the 24M dynamics-suite runs). GAC-<shift> and legacy-<shift>: base dynamics",
            "to the shift at half, same 10 seeds. GACx_*: Greedy AVG + obs soft reset (all shifts) / obs window (gear2x, heavy) / privileged obs stats (gear2x) at the shift.",
            "Generated by scripts/make_gavg_configs.py; analyse with lever_recovery.py --base legacy and --base GAC.",
        ],
        "defaults": {
            "N": N, "seeds": SEEDS, "gamma": 0.99, "beta1": 0.0, "normalize_obs": True, "pnorm": True, "scaled_td": True,
            "legacy_g_reset": True, "n_eval": 2, "video_every": switch, "save_model": True, "save_model_every": 1_000_000,
            "dense_window": [20_000, 200_000],
        },
        "envs": {env: LR[env]},
        "experiments": experiments,
    }
    if smoke:
        for e in experiments:
            e.pop("seeds", None)
            for entry in e.get("schedule", []):
                entry["step"] = 1500
            for a in e.get("on_shift", []):
                if "steps" in a:
                    a["steps"] = 800
        cfg["_comment"] = ["Smoke test of configs/gavg_<env>.json: every condition once on Hopper gear2x, 3000 steps, switch at 1500.",
                           "Login node, ~1 min: CONFIG=configs/gavg_smoke.json bash scripts/trillium/smoke_levers.sh"]
        cfg["defaults"].update(N=3000, seeds=SEEDS[:1], n_eval=1, video_every=1500, dense_window=[500, 1000], checkpoint=1000)
    return cfg


def n_runs(cfg):
    return sum(len(e.get("seeds", cfg["defaults"]["seeds"])) for e in cfg["experiments"])


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--stats_root", default="$SCRATCH/results", help="Folder holding the batch-1 run folders (scratch-<shift>-<env>-<seed>-*)")
    p.add_argument("--targets", default=os.path.join(os.path.dirname(__file__), "..", "configs", "privileged_targets.json"))
    p.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "configs"))
    args = p.parse_args()
    targets = json.load(open(args.targets))
    todo = [(f"gavg_{env.split('-')[0].lower()}", env, False) for env in RUN] + [("gavg_smoke", "Hopper-v4", True)]
    for name, env, smoke in todo:
        cfg = config(env, args.stats_root, targets, smoke)
        path = os.path.join(args.out, f"{name}.json")
        with open(path, "w") as f:
            json.dump(cfg, f, indent=1)
        print(f"{path}: {len(cfg['experiments'])} experiments, {n_runs(cfg)} runs")
