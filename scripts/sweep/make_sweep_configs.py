"""Random hyperparameter search: writes configs/sweep_2026-11-23/sweep_<env>.json, one per env, each filling one Trillium node.

    python scripts/sweep/make_sweep_configs.py [--env Walker2d-v4 ...] [--n_configs 60] [--n_seeds 3] [--N 2000000]
    bash scripts/trillium/submit_sweep.sh                                  # one job per config
    python scripts/sweep/sweep_summary.py --root $SCRATCH/results_sweep    # rank the draws

Each experiment h<hyp_seed> is one draw of (actor_lr, critic_lr, beta1, alpha_lr, gamma), sampled exactly as
incremental_rl/hyp_sweep.py does for that hyp_seed, plus the two README configs (122, 129) as references.
Standard AVG (obs norm, pnorm, scaled TD), legacy G reset. 62 draws x 3 seeds = 186 runs, one node.
Second stage, chosen draws rerun longer with more seeds (writes configs/sweep_long_2026-11-25/sweep_long_<env>.json):
    python scripts/sweep/make_sweep_configs.py --env Walker2d-v4 --hyp_seeds 6 47 10 --N 10000000 --n_seeds 10 --tag long
Locally: python -m incremental_rl.avg_multi_experiment --config configs/sweep_2026-11-23/sweep_<env>.json --results_dir results_sweep/<env> --n_workers 8
"""

import argparse, json, os, datetime
import numpy as np

# steps per run: long enough to rank draws, not to converge
RUN_N = {
    "Reacher-v4": 200_000,
    "Pusher-v5": 500_000,
    "InvertedDoublePendulum-v4": 500_000,
    "Walker2d-v4": 2_000_000,
    "HalfCheetah-v4": 2_000_000,
    "HumanoidStandup-v4": 2_000_000,
    "dmc-finger-spin": 1_000_000,
    "dmc-acrobot-swingup": 1_000_000,
    "dmc-quadruped-run": 2_000_000,
}


def sample(hyp_seed):
    rng = np.random.RandomState(seed=hyp_seed)
    exponent = rng.choice(
        [4, 5, 6]
    )  # same draw order as hyp_sweep.py: exponent, then mantissa
    actor_lr = rng.choice(np.arange(1, 100)) * (1 / np.power(10, exponent))
    exponent = rng.choice([4, 5, 6])
    critic_lr = rng.choice(np.arange(1, 100)) * (1 / np.power(10, exponent))
    beta1 = rng.choice([0.0, 0.9])
    exponent = rng.choice([1, 2, 3, 4, 5])
    alpha_lr = rng.choice(np.arange(1, 10)) * (1 / np.power(10, exponent))
    gamma = rng.choice([0.95, 0.97, 0.99, 0.995, 1])
    return {
        "actor_lr": float(actor_lr),
        "critic_lr": float(critic_lr),
        "beta1": float(beta1),
        "alpha_lr": float(alpha_lr),
        "gamma": float(gamma),
    }


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument(
        "--env", nargs="*", default=list(RUN_N), help="Default: every env in RUN_N"
    )
    p.add_argument("--n_configs", default=60, type=int)
    p.add_argument("--first_hyp_seed", default=0, type=int)
    p.add_argument(
        "--hyp_seeds", nargs="*", default=None, type=int, help="Exactly these draws"
    )
    p.add_argument(
        "--tag", default="", help="Config is sweep_<tag>_<date>/sweep_<tag>_<env>.json"
    )
    p.add_argument(
        "--N", default=None, type=int, help="Steps per run (default: RUN_N[env])"
    )
    p.add_argument("--n_seeds", default=3, type=int)
    p.add_argument("--out", default=None, help="Default: configs/sweep[_<tag>]_<date>, the existing folder or one dated today")
    args = p.parse_args()
    tag = f"{args.tag}_" if args.tag else ""
    if args.out is None:
        configs = os.path.join(os.path.dirname(__file__), "..", "..", "configs")
        name = f"sweep_{args.tag}" if args.tag else "sweep"
        dated = sorted(d for d in os.listdir(configs) if d[:-11] == name)
        args.out = os.path.join(configs, dated[-1] if dated else f"{name}_{datetime.date.today()}")
    os.makedirs(args.out, exist_ok=True)
    hyp_seeds = list(
        range(args.first_hyp_seed, args.first_hyp_seed + args.n_configs)
    ) + [
        122,
        129,
    ]  # + the two README configs
    if args.hyp_seeds:
        hyp_seeds = args.hyp_seeds
    for env in args.env:
        N = args.N or RUN_N[env]
        cfg = {
            "_comment": [
                f"Hyperparameter search on {env}: {len(hyp_seeds)} draws x {args.n_seeds} seeds, {N} steps each.",
                "Generated by scripts/sweep/make_sweep_configs.py; rank with scripts/sweep/sweep_summary.py.",
            ],
            "defaults": {
                "N": N,
                "n_runs": args.n_seeds,
                "normalize_obs": True,
                "pnorm": True,
                "scaled_td": True,
                "legacy_g_reset": True,
                "n_eval": 0,
                "wandb_mode": "disabled",
            },
            "envs": {env: {}},
            "experiments": [{"name": f"h{s:03d}", **sample(s)} for s in hyp_seeds],
        }
        path = os.path.join(args.out, f"sweep_{tag}{env.lower()}.json")
        with open(path, "w") as f:
            json.dump(cfg, f, indent=1)
        print(
            f"{path}: {len(hyp_seeds)} draws, {len(hyp_seeds) * args.n_seeds} runs of {N} steps"
        )
